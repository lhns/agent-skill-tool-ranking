#!/usr/bin/env python3
"""Validate data/*.toml and regenerate the ranking tables.

Usage:
  python scripts/build.py          # validate and write generated files
  python scripts/build.py --check  # validate and fail if generated files are stale

Needs Python 3.11+ (stdlib only). Generated files: ranking/*.md and PROS-AND-CONS.md.
Never edit those by hand; edit data/entries.toml or data/categories.toml instead.
"""
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEIGHTS = {"fit": 3, "effectiveness": 3, "cost": 2, "reliability": 2, "quality": 1, "composability": 1}
EVIDENCE_CAP = {"E0": 1, "E1": 1, "E2": 2, "E3": 3, "E4": 4}
CAPPED = ("effectiveness", "reliability")
GATES = {"Security", "Security (Docker)", "License", "Maintenance", "Platform", "Gate pending"}
GENERATED_NOTE = "<!-- Generated by scripts/build.py from data/*.toml. Do not edit by hand. -->"


def score(e):
    total = sum(e[k] * w for k, w in WEIGHTS.items())
    max_total = 4 * sum(WEIGHTS.values())
    return (total * 200 + max_total) // (2 * max_total)  # round half up


def load():
    cats = tomllib.loads((ROOT / "data/categories.toml").read_text(encoding="utf-8"))["category"]
    entries = tomllib.loads((ROOT / "data/entries.toml").read_text(encoding="utf-8"))["entry"]
    return cats, entries


def validate(cats, entries):
    errors = []
    cat_ids = [c["id"] for c in cats]
    if len(set(cat_ids)) != len(cat_ids):
        errors.append("duplicate category id")
    seen = set()
    for e in entries:
        eid = e.get("id", "?")
        where = f"entry {eid}"
        if eid in seen:
            errors.append(f"{where}: duplicate id")
        seen.add(eid)
        if not e.get("name"):
            errors.append(f"{where}: missing name")
        if "gate" in e:
            if e["gate"] not in GATES:
                errors.append(f"{where}: unknown gate {e['gate']!r} (allowed: {sorted(GATES)})")
            if not e.get("gate_reason"):
                errors.append(f"{where}: gate without gate_reason")
            continue
        if e.get("category") not in cat_ids:
            errors.append(f"{where}: unknown category {e.get('category')!r}")
        for k in WEIGHTS:
            v = e.get(k)
            if not isinstance(v, int) or not 0 <= v <= 4:
                errors.append(f"{where}: {k} must be an integer 0-4, got {v!r}")
        ev = e.get("evidence")
        if ev not in EVIDENCE_CAP:
            errors.append(f"{where}: evidence must be one of {list(EVIDENCE_CAP)}, got {ev!r}")
        else:
            for k in CAPPED:
                if isinstance(e.get(k), int) and e[k] > EVIDENCE_CAP[ev]:
                    errors.append(f"{where}: {k}={e[k]} exceeds the {ev} cap of {EVIDENCE_CAP[ev]}")
        if not e.get("verdict"):
            errors.append(f"{where}: missing verdict")
    return errors


def cell(s):
    return (s or "").replace("|", "\\|").replace("\n", " ")


def label(e):
    base = f"[{cell(e['name'])}]({e['url']})" if e.get("url") else cell(e["name"])
    return f"{base} {cell(e['detail'])}" if e.get("detail") else base


def render(cats, entries):
    ranked = [e for e in entries if "gate" not in e]
    gated = [e for e in entries if "gate" in e]
    by_cat = {c["id"]: sorted((e for e in ranked if e["category"] == c["id"]),
                              key=lambda e: (-score(e), e["id"])) for c in cats}
    files = {}

    idx = ["# Ranking", "", GENERATED_NOTE, "",
           "Scores are provisional. Almost all rest on E0 to E1 evidence, so Effectiveness and Reliability "
           "sit at 1 to 2 for nearly every entry; gaps under 5 points are noise. Columns: Fit, Effectiveness, "
           "Cost, Reliability, Quality, Composability (0 to 4), Evidence, Score (0 to 100). "
           "See [RUBRIC.md](../RUBRIC.md).", "",
           "| Category | Entries | Top entry | Score |", "| --- | --- | --- | --- |"]
    for c in cats:
        rows = by_cat[c["id"]]
        top = rows[0] if rows else None
        idx.append(f"| [{c['title']}]({c['id']}.md) | {len(rows)} | "
                   f"{cell(top['name']) if top else ''} | {score(top) if top else ''} |")
    idx.append(f"| [Listed, not ranked (gate failure)](listed-not-ranked-gate-failure.md) | {len(gated)} | | |")
    files["ranking/README.md"] = idx

    for c in cats:
        lines = [f"# {c['title']}", "", GENERATED_NOTE, "",
                 "| ID | Entry | Type | F | E | C | R | Q | Cmp | Ev | Score | Verdict |",
                 "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
        for e in by_cat[c["id"]]:
            lines.append(f"| {e['id']} | {label(e)} | {cell(e.get('type'))} | {e['fit']} | {e['effectiveness']} | "
                         f"{e['cost']} | {e['reliability']} | {e['quality']} | {e['composability']} | "
                         f"{e['evidence']} | {score(e)} | {cell(e['verdict'])} |")
        if c.get("note"):
            lines += ["", c["note"]]
        files[f"ranking/{c['id']}.md"] = lines

    lines = ["# Listed, not ranked (gate failure)", "", GENERATED_NOTE, "",
             "| ID | Entry | Failed gate | Reason |", "| --- | --- | --- | --- |"]
    for e in sorted(gated, key=lambda e: (e["gate"], e["id"])):
        lines.append(f"| {e['id']} | {label(e)} | {e['gate']} | {cell(e['gate_reason'])} |")
    files["ranking/listed-not-ranked-gate-failure.md"] = lines

    pc = ["# Pros and cons", "", GENERATED_NOTE, "",
          "One row per entry, grouped like the Ranking. Stars are as shown on GitHub when the entry was "
          "evaluated and count as E1 evidence only."]
    for c in cats:
        if not by_cat[c["id"]]:
            continue
        pc += ["", f"## {c['title']}", "", "| ID | Stars | Pros | Cons | Overlaps with |", "| --- | --- | --- | --- | --- |"]
        for e in by_cat[c["id"]]:
            pc.append(f"| {e['id']} | {cell(e.get('stars'))} | {cell(e.get('pros'))} | "
                      f"{cell(e.get('cons'))} | {cell(e.get('overlaps'))} |")
    with_notes = [e for e in gated if e.get("pros") or e.get("cons")]
    if with_notes:
        pc += ["", "## Gate failures", "", "| ID | Stars | Pros | Cons |", "| --- | --- | --- | --- |"]
        for e in sorted(with_notes, key=lambda e: e["id"]):
            pc.append(f"| {e['id']} | {cell(e.get('stars'))} | {cell(e.get('pros'))} | {cell(e.get('cons'))} |")
    files["PROS-AND-CONS.md"] = pc

    return {path: "\n".join(lines) + "\n" for path, lines in files.items()}


def main():
    check = "--check" in sys.argv
    cats, entries = load()
    errors = validate(cats, entries)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)
    files = render(cats, entries)
    expected = set(files)
    existing = {f"ranking/{p.name}" for p in (ROOT / "ranking").glob("*.md")}
    stale = [p for p in sorted(expected)
             if not (ROOT / p).exists() or (ROOT / p).read_text(encoding="utf-8") != files[p]]
    orphans = sorted(existing - expected)
    if check:
        if stale or orphans:
            print("Generated files are out of date; run: python scripts/build.py", file=sys.stderr)
            for p in stale + orphans:
                print(f"  {p}", file=sys.stderr)
            sys.exit(1)
        print(f"OK: {len(entries)} entries, {len(cats)} categories")
        return
    for p in stale:
        (ROOT / p).write_text(files[p], encoding="utf-8", newline="\n")
    for p in orphans:
        (ROOT / p).unlink()
    print(f"Wrote {len(stale)} files, removed {len(orphans)}; {len(entries)} entries, {len(cats)} categories")


if __name__ == "__main__":
    main()
