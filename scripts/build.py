#!/usr/bin/env python3
"""Validate data/*.toml and regenerate the ranking tables and the README stack.

Usage:
  python scripts/build.py          # validate and write generated files
  python scripts/build.py --check  # validate and fail if generated files are stale

Needs Python 3.11+ (stdlib only).
Generated: ranking/*.md (categories, by-job.md), PROS-AND-CONS.md, and the marked sections of README.md.
Edit data/entries.toml, data/categories.toml or data/stack.toml instead.
"""
import re
import sys
import tomllib
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEIGHTS = {"fit": 3, "effectiveness": 3, "cost": 2, "reliability": 2, "quality": 1, "composability": 1}
EVIDENCE_CAP = {"E0": 1, "E1": 1, "E2": 2, "E3": 3, "E4": 4}
CAPPED = ("effectiveness", "reliability")
GATES = {"Security", "Security (Docker)", "License", "Maintenance", "Platform", "Gate pending"}
STATUSES = ["In use", "Trying now", "Up next", "Blocked", "Planned"]
TESTED = ("E3", "E4")  # only these get a score; everything else gets a tier
REVIEWS = {"readme": "README only", "search": "README plus keyword search of the code", "code": "code read"}
TRUSTS = {"official": "published by the vendor of the thing it integrates, or in Anthropic's marketplace",
          "own": "your own project"}
YOUNG_DAYS = 30
TIER_ORDER = ["Stack pick", "Alternate", "Shortlist", "Candidate", "Watch", "No", "Not for you"]
VERDICT_RE = re.compile(r"^(Optional|Watch|Skip)(: .+)?$")
REF_RE = re.compile(r"\{([a-z0-9-]+)\}")
GENERATED_NOTE = "<!-- Generated by scripts/build.py from data/*.toml. Do not edit by hand. -->"
STATUS_LEGEND = {
    "In use": "adopted after logged use, or your own baseline",
    "Trying now": "you are using it; tell the agent how it goes",
    "Up next": "try these first, in table order",
    "Blocked": "picked, but a gate check must pass first",
    "Planned": "picked for its job; install when you work on that kind of project",
}


def score(e):
    total = sum(e[k] * w for k, w in WEIGHTS.items())
    max_total = 4 * sum(WEIGHTS.values())
    return (total * 200 + max_total) // (2 * max_total)  # round half up


def load():
    def read(name):
        return tomllib.loads((ROOT / "data" / name).read_text(encoding="utf-8"))
    return read("categories.toml")["category"], read("entries.toml")["entry"], read("stack.toml")


def tested(e):
    return e.get("evidence") in TESTED


def days_old_at_review(e):
    if "created" not in e:
        return None
    return (date.fromisoformat(e["reviewed"]) - date.fromisoformat(e["created"])).days


def young_untested(e):
    age = days_old_at_review(e)
    return age is not None and age < YOUNG_DAYS and not tested(e)


def stack_roles(stack):
    picks = {p["entry"]: p for p in stack["pick"]}
    alts = {}
    for p in stack["pick"]:
        for a in p.get("alternates", []):
            alts.setdefault(a, p)
    return picks, alts


def validate(cats, entries, stack):
    errors = []
    cat_ids = [c["id"] for c in cats]
    if len(set(cat_ids)) != len(cat_ids):
        errors.append("duplicate category id")
    by_id = {}
    for e in entries:
        eid = e.get("id", "?")
        if eid in by_id:
            errors.append(f"entry {eid}: duplicate id")
        by_id[eid] = e
    picks, alts = stack_roles(stack)

    for e in entries:
        eid = e.get("id", "?")
        where = f"entry {eid}"
        if not e.get("name"):
            errors.append(f"{where}: missing name")
        if "gate" in e:
            if e["gate"] not in GATES:
                errors.append(f"{where}: unknown gate {e['gate']!r} (allowed: {sorted(GATES)})")
            if not e.get("gate_reason"):
                errors.append(f"{where}: gate without gate_reason")
            continue
        if e.get("category") not in cat_ids:
            errors.append(f"{where}: unknown category {e.get('category')!r}")
        for k in WEIGHTS:
            v = e.get(k)
            if not isinstance(v, int) or not 0 <= v <= 4:
                errors.append(f"{where}: {k} must be an integer 0-4, got {v!r}")
        ev = e.get("evidence")
        if ev not in EVIDENCE_CAP:
            errors.append(f"{where}: evidence must be one of {list(EVIDENCE_CAP)}, got {ev!r}")
        else:
            for k in CAPPED:
                if isinstance(e.get(k), int) and e[k] > EVIDENCE_CAP[ev]:
                    errors.append(f"{where}: {k}={e[k]} exceeds the {ev} cap of {EVIDENCE_CAP[ev]}")
        if e.get("review") not in REVIEWS:
            errors.append(f"{where}: review must be one of {list(REVIEWS)}, got {e.get('review')!r}")
        if "trust" in e and e["trust"] not in TRUSTS:
            errors.append(f"{where}: trust must be one of {list(TRUSTS)}, got {e['trust']!r}")
        if e.get("fit_by", "claude") not in ("user", "claude"):
            errors.append(f"{where}: fit_by must be user or claude")
        for k in ("reviewed", "created"):
            if k in e or k == "reviewed":
                try:
                    date.fromisoformat(e.get(k, ""))
                except ValueError:
                    errors.append(f"{where}: {k} must be a YYYY-MM-DD date, got {e.get(k)!r}")
                    e.pop("created", None)
        if ev == "E2" and not e.get("evidence_source"):
            errors.append(f"{where}: E2 needs evidence_source (a link to the independent test)")
        in_stack = eid in picks or eid in alts
        if in_stack and isinstance(e.get("fit"), int) and e["fit"] < 2:
            errors.append(f"{where}: fit below 2 can't be a pick or alternate")
        if in_stack and "reviewed" in e and young_untested(e):
            errors.append(f"{where}: under {YOUNG_DAYS} days old at review and untested, so it can't be in the stack")
        if not in_stack and "reviewed" in e and young_untested(e) and e.get("verdict", "").startswith("Optional"):
            errors.append(f"{where}: under {YOUNG_DAYS} days old at review and untested, so its verdict must be Watch or Skip")
        if in_stack and "verdict" in e:
            errors.append(f"{where}: is in the stack, so remove its verdict (the stack sets it)")
        if not in_stack and e.get("verdict", "").split(":")[0] in ("Skip", "Watch") and ": " not in e["verdict"] \
                and not e.get("cons"):
            errors.append(f"{where}: Skip and Watch need a reason after ': ' or a cons text")
        if not in_stack and not VERDICT_RE.match(e.get("verdict", "")):
            errors.append(f"{where}: verdict must be Optional, Watch or Skip, optionally followed by ': reason'; "
                          f"got {e.get('verdict')!r}. Picks and alternates belong in data/stack.toml")

    jobs = set()
    for p in stack["pick"]:
        where = f"stack job {p.get('job')!r}"
        if p.get("job") in jobs:
            errors.append(f"{where}: duplicate job")
        jobs.add(p.get("job"))
        if p.get("status") not in STATUSES:
            errors.append(f"{where}: status must be one of {STATUSES}, got {p.get('status')!r}")
        for ref in [p.get("entry")] + p.get("alternates", []):
            e = by_id.get(ref)
            if e is None:
                errors.append(f"{where}: unknown entry {ref!r}")
            elif "gate" in e:
                errors.append(f"{where}: {ref} failed a gate and can't be in the stack")
        if p.get("entry") in p.get("alternates", []):
            errors.append(f"{where}: pick is also listed as its own alternate")
        if p.get("entry") in alts:
            errors.append(f"{where}: {p['entry']} is a pick and also an alternate for {alts[p['entry']]['job']!r}")
    if len(picks) != len(stack["pick"]):
        errors.append("stack: the same entry is the pick for more than one job")
    for text in [stack.get("gaps", "")] + [p.get("notes", "") for p in stack["pick"]]:
        for ref in REF_RE.findall(text):
            if ref not in by_id:
                errors.append(f"stack: notes reference unknown entry {{{ref}}}")
    return errors


def cell(s):
    return (s or "").replace("|", "\\|").replace("\n", " ")


def label(e):
    base = f"[{cell(e['name'])}]({e['url']})" if e.get("url") else cell(e["name"])
    return f"{base} {cell(e['detail'])}" if e.get("detail") else base


def link(e):
    return f"[{cell(e['name'])}]({e['url']})" if e.get("url") else cell(e["name"])


def tier(e, picks, alts):
    """Short tier name, used for sorting and counting."""
    if e["id"] in picks:
        return "Stack pick"
    if e["id"] in alts:
        return "Alternate"
    if e["fit"] < 2:
        return "Not for you"
    kind = e["verdict"].split(":")[0]
    if kind == "Skip":
        return "No"
    if kind == "Watch":
        return "Watch"
    return "Shortlist" if e["fit"] >= 3 and e.get("fit_by") == "user" else "Candidate"


def tier_label(e, picks, alts):
    t = tier(e, picks, alts)
    if t == "Stack pick":
        return f"Stack pick ({picks[e['id']]['status']})"
    if t == "Alternate":
        return f"Alternate for {alts[e['id']]['job']}"
    return t


def reason(e):
    v = e.get("verdict", "")
    text = v.split(": ", 1)[1] if ": " in v else ""
    if not text and v.split(":")[0] in ("Skip", "Watch"):
        text = e.get("cons", "").split(";")[0].strip()  # Skip or Watch without a stated reason: first con
    if e["fit"] < 2:
        return f"Fit below 2. {text}" if text else "Fit below 2"
    return text


def shown_score(e):
    return str(score(e)) if tested(e) else "untested"


def evidence_cell(e):
    parts = [e["evidence"]]
    if e.get("trust"):
        parts.append(e["trust"])
    return ", ".join(parts)


def sort_key(e, picks, alts):
    return (TIER_ORDER.index(tier(e, picks, alts)), -score(e) if tested(e) else 0, -e["fit"], e["id"])


ROW_HEAD = ["| ID | Entry | Type | Tier | F | E | C | R | Q | Cmp | Evidence | Review | Score | Reason |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]


def row(e, picks, alts, first=None):
    er = (e["effectiveness"], e["reliability"]) if tested(e) else ("?", "?")
    fit = f"{e['fit']}*" if e.get("fit_by") == "user" else e["fit"]
    lead = f"| {first} " if first is not None else ""
    return (f"{lead}| {e['id']} | {label(e)} | {cell(e.get('type'))} | {cell(tier_label(e, picks, alts))} | {fit} | "
            f"{er[0]} | {e['cost']} | {er[1]} | {e['quality']} | {e['composability']} | {evidence_cell(e)} | "
            f"{e['review']} | {shown_score(e)} | {cell(reason(e))} |")


LEGEND = [
    "How to read the tables:", "",
    "- **Tier** replaces a score for everything untested: **Stack pick** and **Alternate** come from the "
    "[Recommended stack](../README.md#recommended-stack); **Candidate** is fine to try; **Shortlist** is a candidate whose "
    "Fit of 3 or 4 you set yourself; "
    "**Watch** is promising but not ready, or was under 30 days old at review; **No** means don't use it; "
"**Not for you** has Fit below 2 and is not compared further. Fit is guessed by the rater unless marked `*`, "
    "and a blind second rating moved 3 of 15 entries across that line, so tell the agent when a guess is wrong.",
    "- **Score** (0 to 100) appears only with hands-on evidence (E3 or E4). Without it, Effectiveness and Reliability are unknown and shown as `?`.",
    "- **F, C, Q, Cmp** are Fit, Cost (context tokens), Quality, Composability, 0 to 4. They are one rater's reading: "
    "in a blind second rating of 15 entries only 5 to 8 sub-scores per criterion matched exactly, nearly all were within "
    "one point. So a one-point difference means nothing. `*` after Fit means you set it yourself.",
    "- **Evidence**: E0 to E4, plus `official` or `own` as a trust flag. Trust is not evidence of effectiveness.",
    "- **Review** is how deeply the entry was looked at: " + "; ".join(f"`{k}` = {v}" for k, v in REVIEWS.items())
    + ". \"No telemetry found\" from a `search` review is a keyword search, not an audit.",
    "- Within a tier, rows are sorted by Fit, then ID. That order is not a ranking.",
]


def job_candidates(p, ranked, picks, alts):
    members = [p["entry"]] + p.get("alternates", [])
    out = []
    for e in ranked:
        if e["id"] in members or e["fit"] < 2:
            continue
        cites = set(re.findall(r"[a-z0-9]+(?:-[a-z0-9]+)+", e.get("overlaps", "")))
        if p["job"] in e.get("jobs", []) or cites & set(members):
            out.append(e)
    return sorted(out, key=lambda e: sort_key(e, picks, alts))


def render_ranking(cats, entries, stack, picks, alts):
    ranked = [e for e in entries if "gate" not in e]
    gated = [e for e in entries if "gate" in e]
    by_id = {e["id"]: e for e in entries}
    by_cat = {c["id"]: sorted((e for e in ranked if e["category"] == c["id"]),
                              key=lambda e: sort_key(e, picks, alts)) for c in cats}
    files = {}

    idx = ["# Ranking", "", GENERATED_NOTE, "",
           f"{len(ranked)} evaluated entries, {sum(tested(e) for e in ranked)} of them tested hands-on. "
           "Untested entries get a tier, not a score: without hands-on use nobody knows how well a tool works, "
           "and the remaining sub-scores are too coarse to order tools. Compare tools per job in "
           "[by-job.md](by-job.md); categories only group them. See [RUBRIC.md](../RUBRIC.md).", "",
           *LEGEND, "",
           "| Category | Entries | Tested | In stack | Shortlist | Candidate | Watch | No | Not for you |",
           "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for c in cats:
        rows = by_cat[c["id"]]
        n = {t: sum(tier(e, picks, alts) == t for e in rows) for t in TIER_ORDER}
        idx.append(f"| [{c['title']}]({c['id']}.md) | {len(rows)} | {sum(tested(e) for e in rows)} | "
                   f"{n['Stack pick'] + n['Alternate']} | {n['Shortlist']} | {n['Candidate']} | {n['Watch']} | "
                   f"{n['No']} | {n['Not for you']} |")
    idx.append(f"| [Listed, not ranked (gate failure)](listed-not-ranked-gate-failure.md) | {len(gated)} | | | | | | | |")
    files["ranking/README.md"] = idx

    for c in cats:
        lines = [f"# {c['title']}", "", GENERATED_NOTE, "",
                 "Tiers, not a ranking; see the [legend](README.md). Compare per job in [by-job.md](by-job.md).", "",
                 *ROW_HEAD]
        lines += [row(e, picks, alts) for e in by_cat[c["id"]]]
        if c.get("note"):
            lines += ["", c["note"]]
        files[f"ranking/{c['id']}.md"] = lines

    jobs = ["# Candidates per job", "", GENERATED_NOTE, "",
            "One table per job in the [Recommended stack](../README.md#recommended-stack): the pick, its alternates, "
            "and other entries that name the job (`jobs`) or cite the pick or an alternate in `overlaps`. "
            "Entries rated before 2026-10-28 mostly lack those references, so a table can be incomplete. "
            "See the [legend](README.md)."]
    for p in stack["pick"]:
        jobs += ["", f"## {p['job']}", "", "| Role " + ROW_HEAD[0], "| --- " + ROW_HEAD[1]]
        jobs.append(row(by_id[p["entry"]], picks, alts, "Pick"))
        jobs += [row(by_id[a], picks, alts, "Alternate") for a in p.get("alternates", [])]
        jobs += [row(e, picks, alts, "Candidate") for e in job_candidates(p, ranked, picks, alts)]
    files["ranking/by-job.md"] = jobs

    lines = ["# Listed, not ranked (gate failure)", "", GENERATED_NOTE, "",
             "| ID | Entry | Failed gate | Reason | Review |", "| --- | --- | --- | --- | --- |"]
    for e in sorted(gated, key=lambda e: (e["gate"], e["id"])):
        lines.append(f"| {e['id']} | {label(e)} | {e['gate']} | {cell(e['gate_reason'])} | {e['review']} |")
    files["ranking/listed-not-ranked-gate-failure.md"] = lines

    pc = ["# Pros and cons", "", GENERATED_NOTE, "",
          "One row per entry, grouped like the Ranking. This is the most reliable part of the repo: specific, "
          "checkable facts. Stars are as shown when the entry was evaluated; many could not be verified and they "
          "say nothing about effectiveness. The Review column says how deeply each entry was looked at."]
    for c in cats:
        if not by_cat[c["id"]]:
            continue
        pc += ["", f"## {c['title']}", "", "| ID | Entry | Reviewed | Review | Stars | Pros | Cons | Overlaps with |",
               "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for e in by_cat[c["id"]]:
            pc.append(f"| {e['id']} | {link(e)} | {e['reviewed']} | {e['review']} | {cell(e.get('stars'))} | "
                      f"{cell(e.get('pros'))} | {cell(e.get('cons'))} | {cell(e.get('overlaps'))} |")
    with_notes = [e for e in gated if e.get("pros") or e.get("cons")]
    if with_notes:
        pc += ["", "## Gate failures", "", "| ID | Entry | Stars | Pros | Cons |", "| --- | --- | --- | --- | --- |"]
        for e in sorted(with_notes, key=lambda e: e["id"]):
            pc.append(f"| {e['id']} | {link(e)} | {cell(e.get('stars'))} | {cell(e.get('pros'))} | {cell(e.get('cons'))} |")
    files["PROS-AND-CONS.md"] = pc
    return {path: "\n".join(lines) + "\n" for path, lines in files.items()}


def render_readme_sections(cats, entries, stack):
    by_id = {e["id"]: e for e in entries}

    def refs(text):
        return REF_RE.sub(lambda m: link(by_id[m.group(1)]), cell(text))

    def evidence(e):
        text = f"{evidence_cell(e)}, " + (f"score {score(e)}" if tested(e) else "untested")
        return f"[{text}](ranking/{e['category']}.md)"

    def notes(p):
        text = refs(p.get("notes"))
        if p.get("exit_test"):
            text += f" Keep it if: {refs(p['exit_test'])}"
        return text

    order = {s: i for i, s in enumerate(STATUSES)}
    picks = sorted(enumerate(stack["pick"]), key=lambda ip: (order[ip[1]["status"]], ip[0]))
    counts = {s: sum(p["status"] == s for p in stack["pick"]) for s in STATUSES}
    summary = ", ".join(f"{n} {s.lower()}" for s, n in counts.items() if n)

    lines = [f"One pick per job, {len(stack['pick'])} jobs: {summary}. "
             "A pick is the default to try for that job, not a proven winner: only entries marked with a score "
             "have been tested hands-on. Only the jobs loaded globally run in every session; everything else is "
             "installed per project. All candidates for a job are in [ranking/by-job.md](ranking/by-job.md).", "",
             "Status:", "", *[f"- **{s}**: {d}" for s, d in STATUS_LEGEND.items()], "",
             "| Job | Pick | Status | Evidence | Load | Setup notes | Alternates |",
             "| --- | --- | --- | --- | --- | --- | --- |"]
    for _, p in picks:
        e = by_id[p["entry"]]
        alts = ", ".join(link(by_id[a]) for a in p.get("alternates", [])) or "none"
        lines.append(f"| {cell(p['job'])} | {label(e)} | {p['status']} | {evidence(e)} | {cell(p.get('load'))} | "
                     f"{notes(p)} | {alts} |")
    if stack.get("gaps"):
        lines += ["", f"**Jobs with no pick yet:** {refs(stack['gaps'])}"]

    changelog = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8")
    dates = re.findall(r"^\| (\d{4}-\d{2}-\d{2}) \|", changelog, re.M)
    ranked = [e for e in entries if "gate" not in e]
    updated = [f"Last updated {max(dates)} · {len(ranked)} evaluated entries, {sum(tested(e) for e in ranked)} "
               f"tested hands-on, {len(entries) - len(ranked)} gate failures"] if dates else []

    categories = ["  - [Candidates per job](ranking/by-job.md)"]
    categories += [f"  - [{c['title']}](ranking/{c['id']}.md)" for c in cats]
    categories.append("  - [Listed, not ranked (gate failure)](ranking/listed-not-ranked-gate-failure.md)")
    return {"updated": updated, "stack": lines, "categories": categories}


def apply_sections(text, sections):
    for name, lines in sections.items():
        pattern = re.compile(rf"(<!-- BEGIN GENERATED: {name} -->\n).*?(<!-- END GENERATED: {name} -->)", re.S)
        if not pattern.search(text):
            raise SystemExit(f"README.md is missing the markers for generated section {name!r}")
        body = "\n".join(lines) + "\n" if lines else ""
        text = pattern.sub(lambda m: m.group(1) + body + m.group(2), text)
    return text


def main():
    check = "--check" in sys.argv
    cats, entries, stack = load()
    errors = validate(cats, entries, stack)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)
    picks, alts = stack_roles(stack)
    files = render_ranking(cats, entries, stack, picks, alts)
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    files["README.md"] = apply_sections(readme, render_readme_sections(cats, entries, stack))

    existing = {f"ranking/{p.name}" for p in (ROOT / "ranking").glob("*.md")}
    stale = [p for p in sorted(files)
             if not (ROOT / p).exists() or (ROOT / p).read_text(encoding="utf-8") != files[p]]
    orphans = sorted(existing - set(files))
    if check:
        if stale or orphans:
            print("Generated files are out of date; run: python scripts/build.py", file=sys.stderr)
            for p in stale + orphans:
                print(f"  {p}", file=sys.stderr)
            sys.exit(1)
        print(f"OK: {len(entries)} entries, {len(cats)} categories, {len(stack['pick'])} stack jobs")
        return
    for p in stale:
        (ROOT / p).write_text(files[p], encoding="utf-8", newline="\n")
    for p in orphans:
        (ROOT / p).unlink()
    print(f"Wrote {len(stale)} files, removed {len(orphans)}; "
          f"{len(entries)} entries, {len(cats)} categories, {len(stack['pick'])} stack jobs")


if __name__ == "__main__":
    main()
